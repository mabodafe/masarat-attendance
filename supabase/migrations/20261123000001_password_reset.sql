-- Masarat Site Attendance v2.1 — password reset requests + admin settings.
-- Additive only: two new tables, no change to existing ones.

-- ===========================================================================
-- NEW (v2.1): password resets
--   password_resets — one row per reset: an employee's "forgot password" request
--                     (source 'employee_request', starts 'pending') or a reset an
--                     admin did directly (source 'admin', recorded as 'approved').
--                     Doubles as the audit trail of who reset whose password, when.
--   app_settings    — small key/value table for admin-controlled switches.
--                     'password_reset_requests' = 'on' | 'off' (missing = 'on').
-- ===========================================================================
CREATE TABLE IF NOT EXISTS password_resets (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  source       TEXT    NOT NULL CHECK (source IN ('employee_request', 'admin')),
  status       TEXT    NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  requested_at TEXT    NOT NULL,
  decided_at   TEXT,
  decided_by   INTEGER REFERENCES users(id) ON DELETE SET NULL
);
-- At most one open request per employee, so repeated taps cannot flood the queue.
CREATE UNIQUE INDEX IF NOT EXISTS idx_pwreset_one_pending ON password_resets(user_id) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS idx_pwreset_status ON password_resets(status, requested_at);

CREATE TABLE IF NOT EXISTS app_settings (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  updated_by INTEGER REFERENCES users(id) ON DELETE SET NULL
);
